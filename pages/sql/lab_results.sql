CREATE TABLE IF NOT EXISTS `lab_results` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `patient_id` int(11) DEFAULT NULL,
  `patient_identifier` varchar(100) DEFAULT NULL,
  `patient_name` varchar(191) DEFAULT NULL,
  `sample_id` varchar(100) NOT NULL,
  `instrument_run_id` varchar(50) DEFAULT NULL,
  `instrument_name` varchar(100) NOT NULL DEFAULT 'Mindray BS-240 Pro',
  `test_code` varchar(50) NOT NULL,
  `test_name` varchar(191) DEFAULT NULL,
  `result_value` varchar(50) NOT NULL,
  `units` varchar(30) DEFAULT NULL,
  `reference_range` varchar(100) DEFAULT NULL,
  `abnormal_flag` varchar(10) DEFAULT NULL,
  `result_status` varchar(5) DEFAULT NULL,
  `measured_at` datetime DEFAULT NULL,
  `raw_record` text,
  `raw_message` text,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_sample_test` (`sample_id`, `test_code`, `instrument_name`),
  KEY `idx_lab_results_patient_id` (`patient_id`),
  CONSTRAINT `fk_lab_results_patient` FOREIGN KEY (`patient_id`) REFERENCES `patient_info` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
